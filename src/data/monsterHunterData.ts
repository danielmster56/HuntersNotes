const LOCAL_STORAGE_KEY = 'mh_builds_v2';

export function getStoredBuilds(): HunterBuild[] {
  try {
    const data = localStorage.getItem(LOCAL_STORAGE_KEY);
    if (!data) {
      localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(SAMPLE_BUILDS));
      return SAMPLE_BUILDS;
    }
    const parsed = JSON.parse(data);
    return Array.isArray(parsed) && parsed.length > 0 ? parsed : SAMPLE_BUILDS;
  } catch {
    return SAMPLE_BUILDS;
  }
}

export function saveBuildToStorage(newBuild: HunterBuild): HunterBuild[] {
  const current = getStoredBuilds();
  const index = current.findIndex(b => b.id === newBuild.id);
  let updated: HunterBuild[];
  if (index >= 0) {
    updated = [...current];
    updated[index] = newBuild;
  } else {
    updated = [newBuild, ...current];
  }
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(updated));
  } catch (err) {
    console.error('Failed to save to localStorage', err);
  }
  return updated;
}

export function toggleBuildLikeInStorage(buildId: string): { builds: HunterBuild[]; newLikes: number } {
  const current = getStoredBuilds();
  let newLikes = 0;
  const updated = current.map(b => {
    if (b.id === buildId) {
      newLikes = (b.likes || 0) + 1;
      return { ...b, likes: newLikes };
    }
    return b;
  });
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(updated));
  } catch (err) {
    console.error('Failed to update likes', err);
  }
  return { builds: updated, newLikes };
}

export function deleteBuildFromStorage(buildId: string): HunterBuild[] {
  const current = getStoredBuilds();
  const updated = current.filter(b => b.id !== buildId);
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(updated));
  } catch (err) {
    console.error('Failed to delete build', err);
  }
  return updated;
}
